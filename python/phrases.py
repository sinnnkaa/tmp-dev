"""Тексты, которые демон маршрутов произносит по шаблону.

Вынесено из voice_nav_daemon.py отдельным модулем, чтобы сборщик кэша озвучки
(tools/build_voice_cache.sh) мог получить полный список заранее известных фраз,
не поднимая сам демон: у того в импортах vosk и gps, и просто взять из него
функцию нельзя. Второй экземпляр этих формулировок в скрипте кэша означал бы,
что кэш собирается для фраз, которых устройство не произносит, и наоборот —
причём молча.

Модуль намеренно без зависимостей: только стандартная библиотека.
"""

# Поворот объявляется, только когда до него меньше этого расстояния. Отсюда же
# берётся верхняя граница при предварительном синтезе.
TURN_ANNOUNCE_MAX_DIST = 30

_DIRECTIONS = {
    "left": "налево",
    "right": "направо",
    "straight": "прямо",
    "slight left": "немного левее",
    "slight right": "немного правее",
    "sharp left": "резко налево",
    "sharp right": "резко направо",
    "uturn": "развернитесь",
}


def plural_meters(n):
    """Склонение слова "метр" — та же логика, что в get_plural_meters()
    (blind_nav/src/threat_logic.cpp). До этого демон во всех случаях говорил
    "метров": "через двадцать один метров".
    """
    if n % 10 == 1 and n % 100 != 11:
        return "метр"
    if 2 <= n % 10 <= 4 and (n % 100 < 10 or n % 100 >= 20):
        return "метра"
    return "метров"


def direction_to_russian(direction):
    return _DIRECTIONS.get(direction, "прямо")


def turn_phrase(distance_m, direction):
    """Подсказка поворота — ровно в том виде, в каком её произносит демон."""
    return f"Через {distance_m} {plural_meters(distance_m)} {direction_to_russian(direction)}"


def cacheable_phrases():
    """Все фразы демона, текст которых известен заранее.

    Фразы с названием улицы сюда не попадают: множество адресов не ограничено,
    да и звучат они, когда человек стоит на месте, — задержка синтеза там не
    стоит на пути.
    """
    for direction in _DIRECTIONS:
        for distance_m in range(TURN_ANNOUNCE_MAX_DIST):
            yield turn_phrase(distance_m, direction)
