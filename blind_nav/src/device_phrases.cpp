#include "device_phrases.h"

// Формулировки короткие намеренно. Их слышит человек, который прямо сейчас
// идёт и не знает, что прибор перестал видеть; тут важна не вежливость, а то,
// через сколько слогов до него дойдёт суть.
//
// "не видит", а не "сломалась": отказ может быть временным, и ядро само
// пытается его вылечить (см. восстановление в camera_thread_func). Обещать
// поломку, после которой камера через двадцать секунд оживёт, — хуже, чем
// сказать ровно то, что известно.
const char* PHRASE_CAMERA_BLIND = "Камера не видит";
const char* PHRASE_CAMERA_BACK = "Камера снова видит";

std::vector<std::string> device_phrases() {
    return {PHRASE_CAMERA_BLIND, PHRASE_CAMERA_BACK};
}
