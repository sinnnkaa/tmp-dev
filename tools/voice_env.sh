# Общие настройки звукового тракта. Подключается всеми скриптами озвучки,
# записи и монтажа: . "$(dirname "$0")/voice_env.sh"
#
# Смысл файла — в том, что параметры синтеза обязаны совпадать у всех, кто их
# использует. Кэш готовых реплик собирается одним скриптом, а проигрывается
# другим; разъехавшийся length_scale между ними означает, что кэш не совпадёт
# ни с одной живой фразой и молча перестанет работать — устройство просто
# снова начнёт ждать синтеза по пять секунд, ничего не сообщив.
#
# shellcheck shell=bash

# Корень репозитория вычисляется от расположения этого файла, а не задаётся
# строкой: у прогонов записанного видео каталог свой, и жёсткий /root/diplom-cpp
# ломал бы их.
BLINDNAV_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

PIPER_BIN="$BLINDNAV_ROOT/piper/piper/piper"
PIPER_MODEL="$BLINDNAV_ROOT/piper/ru_RU-irina-medium.onnx"
# Речь ускорена относительно дефолта: предупреждение должно уложиться в те
# секунды, что у человека есть на реакцию.
PIPER_LENGTH_SCALE=0.85
# Частота выхода piper для этой модели. Она же у aplay и у сборщика дорожки.
PIPER_RATE=22050

# Частота, на которой пишется диктовка с микрофона гарнитуры. Задаётся в
# voice_nav_daemon.py (HEADSET_RATE) — там её требует и Vosk, и HFP-синк, —
# а здесь нужна монтажу, который читает те же файлы. Языки разные, общий код
# невозможен: расходиться нельзя, иначе диктовка в ролике зазвучит не в том
# темпе, в каком её произносили.
HEADSET_RATE=16000

# Готовые реплики. Загрузка модели piper стоит около 3.5 секунды на каждый
# запуск — больше, чем сам синтез, — поэтому однажды произнесённая фраза
# больше не синтезируется, а играется из файла.
VOICE_CACHE_DIR="$BLINDNAV_ROOT/piper/cache"
# Потолок кэша. Набор предупреждений конечен и занимает десятки мегабайт;
# растут только фразы маршрутов с названиями улиц.
VOICE_CACHE_MAX_BYTES=$((300 * 1024 * 1024))

# Общий лог всего произнесённого — на него смотрят при разборе прогулок.
AUDIO_LOG="$BLINDNAV_ROOT/system_audio.raw"
AUDIO_LOG_MAX_BYTES=$((20 * 1024 * 1024))

# Блокировка звукового устройства между C++ ядром и python-демоном.
# Продублирована в main.cpp (AUDIO_LOCK_PATH) и voice_nav_daemon.py — они на
# других языках и подключить этот файл не могут.
AUDIO_LOCK=/run/lock/blind_nav_audio.lock

VIDEO_DIR="$BLINDNAV_ROOT/videos"
# Тег текущего отрезка записи; публикует C++ ядро (SessionRecorder в main.cpp).
SESSION_TAG_FILE=/dev/shm/nav_session

# У systemd-юнитов нет своего XDG_RUNTIME_DIR, а сервер PulseAudio поднимает
# bt_keeper.sh под root — без этой переменной pactl/aplay не находят сервер и
# молча уходят в сырой ALSA мимо наушников.
export PULSE_RUNTIME_PATH=/run/user/0/pulse

# Адрес гарнитуры. Единственное место в проекте, где он записан: bt_keeper.sh
# по нему подключается, диагностика по нему ищет карту, а python-демон вообще
# не хранит его у себя — спрашивает имя карты у сервера. Раньше адрес был
# выписан в трёх файлах в трёх разных начертаниях (через двоеточия, через
# подчёркивания и в составе имени карты); при замене наушников надо было
# вспомнить про все три, а забытый давал не отказ, а тихую половинчатую
# работу — например, подключение есть, а переключение профиля мимо.
BLINDNAV_BT_MAC="1C:6E:4C:89:E9:32"
# То же самое в начертании PulseAudio (двоеточия заменены подчёркиваниями).
BLINDNAV_BT_MAC_UND="${BLINDNAV_BT_MAC//:/_}"

# Ключ кэша — от текста фразы. Тем самым кэш сам инвалидируется при правке
# формулировки: изменённая фраза просто не найдёт себя в кэше.
voice_cache_key() {
    printf '%s' "$1" | sha1sum | cut -d' ' -f1
}

# Профиль Bluetooth, в котором работает всё устройство. Это HFP, а не A2DP, и
# выбор здесь не про удобство, а про пропускную способность канала.
#
# Измерено 23.08.2026. Контроллер сидит на UART (`hciconfig -a` -> Bus: UART,
# драйвер hci_uart_bcm). За 4.7 секунды проигрывания в A2DP контроллер
# передал 58350 байт — 99 кбит/с, на 39-секундном потоке 87 кбит/с. Журнал
# сервера при этом пишет:
#
#     Bitpool has changed to 7
#     Bitpool has changed to 8
#     ... по одному шагу примерно за полсекунды ...
#     Bitpool has changed to 17
#
# То есть PulseAudio начинает КАЖДУЮ фразу с самого дна шкалы SBC и медленно
# поднимается, упираясь в канал. Bitpool 7 — это 74 кбит/с, 17 — это 130.
# Приличный звук начинается с 35 (229 кбит/с), обычный режим A2DP — 53 (328).
# До них дело не доходит никогда: фраза длится четыре секунды и кончается
# раньше. Отсюда «ужасный звук в наушниках» — не срывы, а постоянное
# пережатие от первого слова до последнего.
#
# HFP решает это тем, что не пытается везти музыку. mSBC — 16 кГц моно,
# 64 кбит/с, постоянные, без всякой адаптации. Измерено на той же плате:
# 68 кбит/с и чисто. Устройство озвучивает только речь, музыку оно не играет
# никогда, так что терять нечего: 16 кГц для речи достаточно.
#
# Чем платим: гарнитура постоянно держит SCO-линк и садится быстрее, а звук
# заметно глуше. Взамен профиль больше не переключается туда-обратно на
# каждую диктовку — микрофон гарнитуры доступен всегда.
#
# Вернуться к A2DP можно одной строкой (или переменной окружения), не трогая
# остальной код:
#     BLINDNAV_BT_PROFILE=a2dp_sink tools/say.sh "проверка"
BLINDNAV_BT_PROFILE="${BLINDNAV_BT_PROFILE:-handsfree_head_unit}"

# Фактическое имя bluez-синка. Указатель default у PulseAudio на этой плате
# указывает на встроенный кодек платы и переставляется при каждой смене
# BT-профиля, поэтому имя спрашивается у сервера. Если гарнитуры нет
# (не подключена, села батарея) — остаётся default: звук уйдёт хоть куда-то.
# Тот же поиск на python живёт в voice_nav_daemon.py (playback_device) — им
# пользуется сигнал готовности микрофона. Правки нужны в обоих местах.
#
# Синк нужного профиля ищется по имени, а не берётся первый попавшийся:
# при переключении профиля старый синк исчезает не мгновенно, и «первый
# bluez_sink» какое-то время может указывать на покидаемый профиль. Играть
# в него — это ровно тот тихий промах, из-за которого раньше «a2dp звучал
# как hfp». Если синка нужного профиля нет, берём любой bluez: глухая речь
# в неверном профиле всё же лучше молчания.
voice_playback_device() {
    local sink
    sink=$(pactl list sinks short 2>/dev/null \
           | awk -F'\t' -v p="$BLINDNAV_BT_PROFILE" \
                 '$2 ~ /^bluez_sink\./ && index($2, p) {print $2; exit}')
    [ -n "$sink" ] || sink=$(pactl list sinks short 2>/dev/null \
                             | awk -F'\t' '$2 ~ /^bluez_sink\./ {print $2; exit}')
    if [ -n "$sink" ]; then printf 'pulse:%s' "$sink"; else printf 'default'; fi
}
