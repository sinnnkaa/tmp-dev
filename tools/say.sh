#!/bin/bash
# Единая точка озвучки: произносит фразу в гарнитуру.
#
# Раньше одинаковый конвейер "piper --output-raw | tee | aplay" был выписан
# дважды — в main.cpp через std::system и в voice_nav_daemon.py через
# subprocess. Любая правка звукового тракта доходила только до одной половины
# системы (так C++ ядро и осталось с "-D default", когда демон уже адресовался
# bluez-синку по имени). Теперь тракт один и правится в одном месте.
#
# Готовые реплики берутся из кэша (tools/build_voice_cache.sh). Синтез на этой
# плате стоит около 5.5 секунды на короткую фразу, из них ~3.5 — загрузка
# модели piper при каждом запуске; из кэша та же фраза начинает звучать за
# десятки миллисекунд. Промах кэша не ошибка: фраза синтезируется на месте и
# тут же в кэш и попадает, поэтому второй раз она уже мгновенная.
#
# Вторая задача — запись реплики для автомонтажа (tools/montage_session.sh):
# сохраняем звучавший PCM и момент, когда звук реально пошёл в наушник.
#
# Использование: say.sh "текст фразы" [core|nav]
#   core — предупреждение об опасности от C++ ядра
#   nav  — голос маршрута от python-демона
set -u

. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/voice_env.sh"

TEXT="${1:-}"
SRC="${2:-core}"
[ -z "$TEXT" ] && exit 0

DEV=$(voice_playback_device)

KEY=$(voice_cache_key "$TEXT")
CACHED="$VOICE_CACHE_DIR/$KEY.raw"

if [ ! -s "$CACHED" ]; then
    mkdir -p "$VOICE_CACHE_DIR"
    # Через временный файл: иначе оборванный на середине синтез (питание,
    # вытесняющий pkill от предупреждения) оставил бы в кэше обрезанную фразу
    # навсегда — она бы проигрывалась вместо целой и никогда не пересинтезировалась.
    TMP_UTT="$VOICE_CACHE_DIR/$KEY.raw.$$"
    printf '%s\n' "$TEXT" \
        | "$PIPER_BIN" --model "$PIPER_MODEL" --length_scale "$PIPER_LENGTH_SCALE" \
                       --output-raw 2>/dev/null > "$TMP_UTT"
    if [ -s "$TMP_UTT" ]; then
        mv "$TMP_UTT" "$CACHED"
    else
        rm -f "$TMP_UTT"
        exit 1
    fi
fi

# Копия реплики рядом с записью прогулки. Тег текущего отрезка публикует C++
# ядро; если запись не идёт, реплика никуда не сохраняется — озвучка не должна
# зависеть от того, пишется ли видео.
TAG=""
[ -r "$SESSION_TAG_FILE" ] && TAG=$(cat "$SESSION_TAG_FILE" 2>/dev/null)
SPEECH_DIR="$VIDEO_DIR/speech_$TAG"
UTT=""
if [ -n "$TAG" ] && [ -d "$SPEECH_DIR" ]; then
    UTT="$SPEECH_DIR/utt_$(date +%s%N)_${SRC}.raw"
    # Жёсткая ссылка, а не копия: тот же раздел, реплика повторяется десятки
    # раз за прогулку, и каждая копия стоила бы сотню килобайт записи на карту.
    ln "$CACHED" "$UTT" 2>/dev/null || cp "$CACHED" "$UTT" 2>/dev/null || UTT=""
fi

if [ -f "$AUDIO_LOG" ] && [ "$(stat -c%s "$AUDIO_LOG" 2>/dev/null || echo 0)" -gt "$AUDIO_LOG_MAX_BYTES" ]; then
    : > "$AUDIO_LOG"
fi
cat "$CACHED" >> "$AUDIO_LOG"

# Метка времени ставится последним действием перед aplay, уже после записи в
# лог: монтаж кладёт реплику на видеодорожку именно по ней, и всё, что успеет
# вклиниться между меткой и звуком, станет ошибкой синхронизации.
[ -n "$UTT" ] && printf '%s\t%s\t%s\n' "$(date +%s.%N)" "$(basename "$UTT")" "$TEXT" >> "$SPEECH_DIR/speech.tsv"

# Файл передаётся aplay аргументом, а не через пайп, ровно ради того, чтобы
# путь к нему был виден в командной строке процесса. По нему предупреждение об
# опасности находит и снимает звучащую подсказку маршрута (см. main.cpp).
# Прежний шаблон опознавал воспроизведение по "-r 22050" — то есть по частоте
# дискретизации модели, заданной совсем в другом файле: сменили бы голос на
# модель с другой частотой, и вытеснение молча перестало бы работать.
aplay -D "$DEV" -r "$PIPER_RATE" -f S16_LE -t raw -c 1 "$CACHED" 2>/dev/null
