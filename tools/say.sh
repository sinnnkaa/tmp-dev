#!/bin/bash
# Единая точка озвучки: произносит фразу в гарнитуру.
#
# Раньше одинаковый конвейер "piper --output-raw | tee | aplay" был выписан
# дважды — в main.cpp через std::system и в voice_nav_daemon.py через
# subprocess. Любая правка звукового тракта доходила только до одной половины
# системы (так C++ ядро и осталось с "-D default", когда демон уже адресовался
# bluez-синку по имени). Теперь тракт один и правится в одном месте.
#
# Готовые реплики берутся из кэша (tools/build_voice_cache.sh). Синтез на этой
# плате стоит около 5.5 секунды на короткую фразу, из них ~3.5 — загрузка
# модели piper при каждом запуске; из кэша та же фраза начинает звучать за
# десятки миллисекунд. Промах кэша не ошибка: фраза синтезируется на месте и
# тут же в кэш и попадает, поэтому второй раз она уже мгновенная.
#
# Вторая задача — запись реплики для автомонтажа (tools/montage_session.sh):
# сохраняем звучавший PCM и момент, когда звук реально пошёл в наушник.
#
# Использование: say.sh "текст фразы" [core|nav]
#   core — предупреждение об опасности от C++ ядра
#   nav  — голос маршрута от python-демона
#
# Код возврата:
#   0 — фраза прозвучала (целиком или до вытеснения предупреждением)
#   1 — звука не было: синтез не удался или aplay отказал на обоих устройствах.
#       Для устройства, ведущего незрячего человека, это отказ защитной
#       функции; подробности уходят в журнал. Ядро запускает скрипт в фоне и
#       кода не видит — журнал здесь единственный способ узнать о немоте.
set -u

. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/voice_env.sh"

TEXT="${1:-}"
SRC="${2:-core}"
[ -z "$TEXT" ] && exit 0

DEV=$(voice_playback_device)

KEY=$(voice_cache_key "$TEXT")
CACHED="$VOICE_CACHE_DIR/$KEY.raw"

if [ ! -s "$CACHED" ]; then
    mkdir -p "$VOICE_CACHE_DIR"
    # Через временный файл: иначе оборванный на середине синтез (питание,
    # вытесняющий pkill от предупреждения) оставил бы в кэше обрезанную фразу
    # навсегда — она бы проигрывалась вместо целой и никогда не пересинтезировалась.
    TMP_UTT="$VOICE_CACHE_DIR/$KEY.raw.$$"
    printf '%s\n' "$TEXT" \
        | "$PIPER_BIN" --model "$PIPER_MODEL" --length_scale "$PIPER_LENGTH_SCALE" \
                       --output-raw 2>/dev/null > "$TMP_UTT"
    if [ -s "$TMP_UTT" ]; then
        mv "$TMP_UTT" "$CACHED"
    else
        rm -f "$TMP_UTT"
        exit 1
    fi
fi

# Копия реплики рядом с записью прогулки. Тег текущего отрезка публикует C++
# ядро; если запись не идёт, реплика никуда не сохраняется — озвучка не должна
# зависеть от того, пишется ли видео.
TAG=""
[ -r "$SESSION_TAG_FILE" ] && TAG=$(cat "$SESSION_TAG_FILE" 2>/dev/null)
SPEECH_DIR="$VIDEO_DIR/speech_$TAG"
UTT=""
if [ -n "$TAG" ] && [ -d "$SPEECH_DIR" ]; then
    UTT="$SPEECH_DIR/utt_$(date +%s%N)_${SRC}.raw"
    # Жёсткая ссылка, а не копия: тот же раздел, реплика повторяется десятки
    # раз за прогулку, и каждая копия стоила бы сотню килобайт записи на карту.
    ln "$CACHED" "$UTT" 2>/dev/null || cp "$CACHED" "$UTT" 2>/dev/null || UTT=""
fi

if [ -f "$AUDIO_LOG" ] && [ "$(stat -c%s "$AUDIO_LOG" 2>/dev/null || echo 0)" -gt "$AUDIO_LOG_MAX_BYTES" ]; then
    : > "$AUDIO_LOG"
fi

# ---------------------------------------------------------------------------
# Воспроизведение с отчётом о результате.
#
# Раньше эти строки выглядели так: запись в общий аудиолог, метка в speech.tsv,
# и следом `aplay ... 2>/dev/null` — код возврата не проверялся, stderr
# выбрасывался, а ядро запускает скрипт в фоне и результата не ждёт. То есть
# если гарнитура отвалилась, синк исчез или устройство занято, предупреждение
# об опасности молча не звучало, и узнать об этом было неоткуда: в журнале
# пусто, а speech.tsv уже содержал запись о фразе.
#
# Отсюда же расходились разборы прогулок. speech.tsv фиксировал НАМЕРЕНИЕ
# сказать, а читали его как летопись того, что человек услышал.
#
# Теперь строка в индекс пишется после воспроизведения — но с меткой, снятой
# ДО него. Это не мелочь: монтаж кладёт реплику на видеодорожку именно по
# метке, и поставь мы её по факту окончания, весь голос в ролике уехал бы на
# длительность фразы вперёд. Смысл переноса не в метке, а в самой строке:
# существует она теперь только тогда, когда звук действительно шёл.
# ---------------------------------------------------------------------------

PLAY_START=""
ERR_FILE=$(mktemp /dev/shm/say_err_XXXXXX 2>/dev/null || mktemp)

cleanup() { [ -n "${ERR_FILE:-}" ] && rm -f "$ERR_FILE"; }

# Заносит прозвучавшую реплику в индекс и в общий аудиолог.
# Четвёртая колонка — сколько секунд звук шёл на самом деле. Она отличается от
# длины файла, когда фразу вытеснило предупреждение об опасности: в ролике
# такая реплика сейчас звучит целиком, хотя человек услышал её начало.
record_played() {
    local end dur
    [ -n "$PLAY_START" ] || return 0
    cat "$CACHED" >> "$AUDIO_LOG"
    [ -n "$UTT" ] || return 0
    end=$(date +%s.%N)
    dur=$(awk -v a="$PLAY_START" -v b="$end" 'BEGIN{d=b-a; if(d<0)d=0; printf "%.3f", d}')
    printf '%s\t%s\t%s\t%s\n' "$PLAY_START" "$(basename "$UTT")" "$TEXT" "$dur" \
        >> "$SPEECH_DIR/speech.tsv"
    UTT=""   # второй раз ту же реплику в индекс не пишем
}

# Ядро снимает звучащую подсказку маршрута, когда надо сказать об опасности, и
# бьёт при этом и по aplay, и по самому скрипту. Это штатный сценарий, а не
# сбой: перехватываем сигнал, чтобы успеть записать, сколько реплика реально
# звучала. Без перехвата скрипт умирал бы молча и вытесненные реплики
# пропадали из индекса совсем.
on_term() { record_played; cleanup; exit 0; }
trap on_term TERM INT
trap cleanup EXIT

# Файл передаётся aplay аргументом, а не через пайп, ровно ради того, чтобы
# путь к нему был виден в командной строке процесса. По нему предупреждение об
# опасности находит и снимает звучащую подсказку маршрута (см. main.cpp).
# Прежний шаблон опознавал воспроизведение по "-r 22050" — то есть по частоте
# дискретизации модели, заданной совсем в другом файле: сменили бы голос на
# модель с другой частотой, и вытеснение молча перестало бы работать.
play_once() {
    PLAY_START=$(date +%s.%N)
    aplay -D "$1" -r "$PIPER_RATE" -f S16_LE -t raw -c 1 "$CACHED" 2>"$ERR_FILE"
}

play_once "$DEV"
RC=$?

# Код 128 и выше — это смерть от сигнала, то есть вытеснение предупреждением.
# Повторять такую фразу нельзя ни в коем случае: её оборвали намеренно, и
# «спасённая» подсказка маршрута зазвучала бы сразу после предупреждения об
# опасности, поверх которого её и снимали.
if [ "$RC" -ne 0 ] && [ "$RC" -lt 128 ] && [ "$DEV" != "default" ]; then
    echo "[Озвучка] aplay отказал (код $RC) на устройстве $DEV," \
         "пробую default: $(tr '\n' ' ' < "$ERR_FILE")" >&2
    # Гарнитуры может не быть вовсе (выключена, села батарея). Динамик платы —
    # плохая замена наушнику, но человек хотя бы услышит предупреждение.
    play_once default
    RC=$?
fi

if [ "$RC" -eq 0 ] || [ "$RC" -ge 128 ]; then
    [ "$RC" -ge 128 ] && echo "[Озвучка] Фраза вытеснена предупреждением: $TEXT" >&2
    record_played
    exit 0
fi

# Досюда доходим, только если звука не было вообще. Для устройства, которое
# ведёт незрячего человека, это отказ защитной функции — он обязан быть виден
# в журнале, а не выясняться потом по молчанию на записи.
echo "[Озвучка] ФРАЗА НЕ ПРОЗВУЧАЛА (код $RC): $TEXT" >&2
[ -s "$ERR_FILE" ] && echo "[Озвучка] aplay: $(tr '\n' ' ' < "$ERR_FILE")" >&2
# Ссылку на реплику убираем: иначе она попала бы в ролик как прозвучавшая.
[ -n "$UTT" ] && rm -f "$UTT"
exit 1
